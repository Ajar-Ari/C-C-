#include <stdio.h>

#define MAX_STUDENTS 50 // 입력 가능한 최대 학생 수 / Максимальное количество студентов, которое можно ввести (указать)

// 버블 정렬 (포인터로 배열에 접근) / Пузырьковая сортировка (доступ к массиву через указатели)
void bubbleSort(int *p, int n)
{
    for (int i = 0; i < n - 1; i++)
    {
        for (int j = 0; j < n - i - 1; j++)
        {
            if (*(p + j) > *(p + j + 1))
            {
                int temp = *(p + j);
                *(p + j) = *(p + j + 1);
                *(p + j + 1) = temp;
            }
        }
    }
}

int main()
{
    int scores[MAX_STUDENTS]; // 성적을 저장할 배열 / Массив для хранения оценок
    int *ptr = scores;        // 배열을 가리키는 포인터 / Указатель на массив
    int n;

    printf("학생 수를 입력하세요 (1~%d): ", MAX_STUDENTS);
    scanf("%d", &n);

    // 입력 범위를 벗어나면 오류 메시지 출력 후 종료
    // Если ввод выходит за допустимый диапазон, вывести сообщение об ошибке и завершить программу
    if (n < 1 || n > MAX_STUDENTS)
    {
        printf("오류: 학생 수는 1~%d 사이여야 합니다.\n", MAX_STUDENTS);
        return 1;
    }

    // 포인터를 사용하여 성적 입력 / Ввод оценок с использованием указателя
    for (int i = 0; i < n; i++)
    {
        printf("%d번 학생 성적: ", i + 1);
        scanf("%d", ptr + i);
    }

    bubbleSort(ptr, n);

    printf("정렬된 성적: ");
    for (int i = 0; i < n; i++)
    {
        printf("%d ", *(ptr + i));
    }
    printf("\n");

    printf("최고 성적: %d\n", *(ptr + n - 1)); // 오름차순이므로 마지막이 최댓값 / Так как массив отсортирован по возрастанию, последний элемент является максимальным значением
    printf("최하 성적: %d\n", *ptr);           // 첫 번째가 최솟값 / Первый элемент — минимальное значение

    return 0;
}